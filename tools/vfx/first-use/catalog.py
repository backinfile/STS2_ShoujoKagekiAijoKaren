"""Generate/check the exhaustive VFX resource catalog. No game or user files are changed."""
from pathlib import Path
import argparse,json,re,sys
ROOT=Path(__file__).resolve().parents[3]
GENERATED=ROOT/'src/Core/Vfx/KarenVfxCatalog.g.cs'
OWNER_FILE=Path(__file__).with_name('resource-owners.json')
# Include complete directories, so dynamically assembled resource paths are covered too.
DIRS=['images/vfx','images/packed/vfx','materials','shaders','themes','scenes',
      'images/ui/combat','images/ui/flower','images/ui/top_bar','images/powers','ShoujoKagekiAijoKaren/audio','ShoujoKagekiAijoKaren/video']
EXTS={'.png','.jpg','.tres','.tscn','.gdshader','.wav','.ogg','.mp3','.ogv'}
def assets():
 result={p.relative_to(ROOT).as_posix() for d in DIRS for p in (ROOT/d).rglob('*') if p.suffix.lower() in EXTS}
 for p in (ROOT/'src').rglob('*.cs'):
  if p==GENERATED:continue
  for path in re.findall(r'"res://([^"{}]+)"',p.read_text(encoding='utf-8-sig')):
   if (ROOT/path).is_file() and Path(path).suffix.lower() in EXTS:result.add(path)
 result.update(["scenes/vfx/vfx_shiv_throw.tscn", "debug_audio/slash_attack.mp3"]+["images/atlases/ui_atlas.sprites/card/card_frame_"+k+"_s.tres" for k in ["attack","skill","power","quest","ancient"]])
 return sorted(result)
def effects():
 result={}
 for p in (ROOT/'src').rglob('*.cs'):
  if p==GENERATED:continue
  s=p.read_text(encoding='utf-8-sig')
  ns=re.search(r'namespace ([\w.]+);',s)
  if not ns:continue
  for match in re.finditer(r'(?:partial |sealed |abstract )*class ((?:NKaren|NDisableRelic|SN)\w+|KarenLightRibbon)',s):
   cls=match[1]
   if s[s.rfind("\n",0,match.start())+1:match.start()].startswith("    "):
    parent=re.findall(r"^.*?class (\w+)",s[:match.start()],re.M)[0]
    cls=parent+"+"+cls
   if '/Vfx/' in p.as_posix() or '/ShineSystem/Nodes/' in p.as_posix() or '/GodotScripts/Node/' in p.as_posix():
    result.setdefault(ns[1]+'.'+cls,[]).append(p.relative_to(ROOT).as_posix())
 return dict(sorted(result.items()))
def owner_at(code,position):
 # Ignore braces in C# strings/comments, then locate the enclosing class bodies.
 literal=re.compile(r'"""[\s\S]*?"""|@"(?:[^"]|"")*"|"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|//[^\n]*|/\*[\s\S]*?\*/')
 clean=literal.sub(lambda m: ''.join('\n' if c=='\n' else ' ' for c in m[0]),code)
 owners=[]
 for match in re.finditer(r'\bclass (\w+)[^{;]*\{',clean):
  opening=match.end()-1
  if opening>=position:continue
  depth=1;end=opening+1
  while end<len(clean) and depth:
   if clean[end]=='{':depth+=1
   elif clean[end]=='}':depth-=1
   end+=1
  if position<end:owners.append(match[1])
 assert owners,'Resource declaration outside class'
 return '.'.join(owners)

def content():
 paths=assets();owners=json.loads(OWNER_FILE.read_text());fx=effects()
 text='// Generated by tools/vfx/first-use/catalog.py; run --check before releasing.\nusing Godot;\nusing System.Collections.Generic;\n\nnamespace ShoujoKagekiAijoKaren.src.Core.Vfx;\n\ninternal static class KarenVfxCatalog\n{\n'
 text+='    internal static readonly string[] AssetPaths =\n    [\n'+''.join('        "res://'+p+'",\n' for p in paths)+'    ];\n'
 text+='    internal static readonly string[] EffectTypes =\n    [\n'+''.join('        "'+cls+'",\n' for cls in fx)+'    ];\n'
 text+='    internal static IEnumerable<Resource> PrepareSharedResources()\n    {\n'
 for owner in owners:
  text+='        '+owner+'.PrepareResources();\n        foreach (var r in '+owner+'.PreparedResources) if (r != null) yield return r;\n'
 text+='    }\n}\n'
 return text,dict(effects=fx,resource_owners=owners,assets=paths)
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');p.add_argument('--report',type=Path);a=p.parse_args()
 expected,report=content()
 if a.check:
  assert GENERATED.read_text(encoding='utf-8')==expected,'VFX coverage changed; update resource-owners.json as needed, then run catalog.py'
  # Every class exposing preparation must be registered; no reflection-based blanket initialization.
  actual=set()
  for f in (ROOT/'src').rglob('*.cs'):
   s=f.read_text(encoding='utf-8-sig')
   if 'internal static void PrepareResources()' in s:
    ns=re.search(r'namespace ([\w.]+);',s)[1]
    for m in re.finditer(r'internal static void PrepareResources\(\)',s):
     cls=owner_at(s,m.start());actual.add(ns+'.'+cls)
  # New visual classes must not silently introduce lazy static resources without preparation.
  for f in (ROOT/'src').rglob('*.cs'):
   if '/Vfx/' not in f.as_posix() or f.name in ('KarenVfxWarmup.cs','KarenVfxCatalog.g.cs'):continue
   code=f.read_text(encoding='utf-8-sig')
   namespace=re.search(r'namespace ([\w.]+);',code)[1]
   for field in re.finditer(r'\bstatic (?:readonly )?(?:Godot\.)?(?:Texture2D|GradientTexture2D|GradientTexture1D|Shader|CurveTexture|ShaderMaterial|ParticleProcessMaterial)\b',code):
    owner=owner_at(code,field.start())
    assert namespace+'.'+owner in actual,'Unprepared static visual resource owner: '+f.relative_to(ROOT).as_posix()+':'+owner
  assert actual==set(report['resource_owners']),{'unregistered':sorted(actual-set(report['resource_owners'])),'stale':sorted(set(report['resource_owners'])-actual)}
 else:GENERATED.write_text(expected,encoding='utf-8')
 if a.report:a.report.parent.mkdir(parents=True,exist_ok=True);a.report.write_text(json.dumps(report,ensure_ascii=False,indent=2),encoding='utf-8')
 print(f"VFX catalog: {len(report['effects'])} types, {len(report['resource_owners'])} shared owners, {len(report['assets'])} assets; {'checked' if a.check else 'generated'}")
if __name__=='__main__':main()
